export function optionsFor(source, lookups) {
  const map = {
    clubs: () => lookups.clubs.map((item) => [item.id, item.name]),
    members: () => lookups.members.map((item) => [item.id, item.full_name + ' · ' + item.member_code]),
    membersOptional: () => [['', 'All members'], ...lookups.members.map((item) => [item.id, item.full_name])],
    facilities: () => lookups.facilities.filter((item) => item.bookable).map((item) => [item.id, item.name]),
    events: () => lookups.events.map((item) => [item.id, item.title]),
    packages: () => lookups.packages.map((item) => [item.id, item.name]),
    categories: () => lookups.masters.filter((item) => item.type === 'membership_category').map((item) => [item.name, item.name]),
    natures: () => lookups.masters.filter((item) => item.type === 'business_nature').map((item) => [item.name, item.name]),
    statuses: () => [['active', 'Active'], ['pending', 'Pending'], ['inactive', 'Inactive']],
    bookingStatuses: () => [['pending', 'Pending'], ['approved', 'Approved'], ['booked', 'Booked'], ['rejected', 'Rejected'], ['cancelled', 'Cancelled']],
    enquiryStatuses: () => [['open', 'Open'], ['closed', 'Closed']],
    ticketStatuses: () => [['valid', 'Valid'], ['used', 'Used'], ['cancelled', 'Cancelled']],
    directions: () => [['debit', 'Charge (dues increase)'], ['credit', 'Receipt (dues decrease)']],
    icons: () => [['card', 'Card'], ['handshake', 'Handshake'], ['wallet', 'Wallet'], ['calendar', 'Calendar'], ['business', 'Office']],
    masterTypes: () => lookups.masterTypes.map((item) => [item.id, item.label]),
  };
  return (map[source] || (() => []))();
}
